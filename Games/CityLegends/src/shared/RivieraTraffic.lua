-- is piece k (from point k to k + 1) inside a lane's point ranges? (true = all of it, nil = none)
local function inRanges(r: any, k: number): boolean
	if r == true then
		return true
	elseif type(r) ~= "table" then
		return false
	end
	for i = 1, #r - 1, 2 do
		if k >= r[i] and k < r[i + 1] then
			return true
		end
	end
	return false
end

local cached = nil
function RivieraTraffic.build()
	if cached then
		return cached
	end
	local ok, data = pcall(function()
		return require(script.Parent:WaitForChild("RivieraLanes", 5))
	end)
	if not ok or type(data) ~= "table" then
		return nil
	end
	-- (2026-11-04) the Riviera Highway's and the Summit Pass's lanes live in their own module (Studio
	-- refuses a script over 200,000 characters): numbered on from RivieraLanes', added to its lists
	local okH, extra = pcall(function()
		return require(script.Parent:WaitForChild("RivieraLanesHighway", 2))
	end)
	if okH and type(extra) == "table" and extra.first == #data.lanes + 1 then
		local lanesAll, linksAll = table.clone(data.lanes), table.clone(data.links)
		for _, l in extra.lanes do
			table.insert(lanesAll, l)
		end
		for _, k in extra.links do
			table.insert(linksAll, k)
		end
		data = { lanes = lanesAll, links = linksAll }
	end
	-- (2026-11-17) the old 1.6 Yangon's lanes (YangonLanes, YangonLanes2, YangonLanesB*) went with its map
	-- (2026-11-16, the 1:1 Yangon frame: tools/yangon/city/roads.py P1 + lanes_1to1.py) the pilot districts' lanes in
	-- modules YangonLanes1to1_<k>, numbered from 1 within the 1:1 set (`first`, links too) so they don't depend on the
	-- old map's modules; added after everything above with that count as the offset. The frame lies far from the old
	-- map (Config.isYangon1to1At), so Traffic's spawns near the player keep each map's cars on its own lanes.
	do
		local base = #data.lanes
		local la, li = nil, nil
		for k = 1, 60 do
			local m = script.Parent:FindFirstChild("YangonLanes1to1_" .. k)
			if not m then
				break
			end
			local okB, mod = pcall(require, m)
			local count = if la then #la - base else 0
			if okB and type(mod) == "table" and mod.first == count + 1 then
				if not la then
					la, li = table.clone(data.lanes), table.clone(data.links)
				end
				for _, l in mod.lanes do
					table.insert(la, l)
				end
				for _, x in mod.links do
					table.insert(li, { x[1] + base, x[2], x[3] + base, x[4] })
				end
			else
				warn("RivieraTraffic: YangonLanes1to1_" .. k .. " is out of step; the 1:1 frame's traffic is incomplete")
				break
			end
		end
		if la then
			-- (2026-11-22) the Hledan flyover's new continuous deck: lanes lifted onto it
			local fix = script.Parent:FindFirstChild("YangonDeckFix")
			local okF, modF = pcall(function()
				return fix and require(fix)
			end)
			if okF and modF then
				modF.apply(la)
			end
			data = { lanes = la, links = li }
		end
	end
	local dataLanes, dataLinks = oneLaneStreets(data)
	dataLinks = mergeRouteEnds(dataLanes, dataLinks)
	local all, lanes = {}, {}
	local pieces = {} -- [laneIndex][pointIndex] = the piece starting at that point
	-- (2026-11-24) a 1:1 piece that drops or climbs like a cliff (YangonDeckFix.cliff) is never driven onto
	local cliffOk, cliffMod = pcall(function()
		local m = script.Parent:FindFirstChild("YangonDeckFix")
		return m and require(m)
	end)
	local isCliff = if cliffOk and cliffMod and cliffMod.cliff then cliffMod.cliff else nil
	for li, l in dataLanes do
		local pts = l.pts
		local n = #pts // 3
		local row = {}
		pieces[li] = row
		if l.skip then
			continue -- (a street's dropped lane 2)
		end
		-- (the main routes run a little faster than the town streets, never highway pace)
		local speedK = if l.kind == "route" then 1 else 0.85
		for k = 1, n - 1 do
			local a = Vector3.new(pts[3 * k - 2], pts[3 * k - 1], pts[3 * k])
			local b = Vector3.new(pts[3 * k + 1], pts[3 * k + 2], pts[3 * k + 3])
			local seg = newSegment(all, a, (a + b) / 2, b, "lane")
			seg.lane = l.lane
			seg.road = l.road -- (the server's start spots use it)
			seg.route = l.kind == "route" -- the three long routes (yellow on the map)
			seg.rivHighway = l.highway == true -- the Riviera Highway (Traffic keeps few cars on it)
			seg.speedK = speedK
			if l.yangon then
				-- (Yangon v5, d9_lanes.py: `outer` / `median` = point ranges { from, to, ... } where this lane is a
				-- road's outermost (the start spots) and where a raised median runs beside it (no lane
				-- splitting onto it), or true for the whole lane)
				local s = seg :: any
				s.outer = inRanges(l.outer, k)
				s.median = inRanges(l.median, k)
			end
			row[k] = seg
			if l.yangon and isCliff and isCliff(a, b) then
				-- (no way in: the lane's pieces before it end here and are pruned back to the last junction; no spawns on it)
				(seg :: any).cliff = true
				continue
			end
			table.insert(lanes, seg)
			if k > 1 then
				table.insert(row[k - 1].next, seg)
			end
		end
	end
	-- turns between lanes: a curve from the end of one piece to the start of another
	-- (owner, 2026-11-03: "some cars are turning left and turning right, they're not programmed
	-- properly"): where a lane's end and the next lane's start sit too close for the angle, the curve
	-- had to swing one way and then back (89 of 414 turns turned both ways). Now the turn may leave a
	-- piece or two earlier and join a piece or two later, picking the nearest pair whose way in and
	-- way out meet ahead of both: one clean arc
	-- (2026-11-04, "they dont know how to turn properly") first a strict search, wider (up to 3 pieces
	-- back and 5 on): the arc must be balanced, its corner at least 6 studs from both ends and neither
	-- leg under 0.3 of the other (a lopsided arc ran straight and then snapped round in its last
	-- studs); only if none fits, the loose search as before
	local function corner(before, after, strict: boolean?): Vector3?
		local p0, p2 = before.p2, after.p0
		local d = (p2 - p0).Magnitude
		local dirIn = (before.p2 - before.p0) * Vector3.new(1, 0, 1)
		local dirOut = (after.p2 - after.p0) * Vector3.new(1, 0, 1)
		if dirIn.Magnitude < 0.1 or dirOut.Magnitude < 0.1 then
			return nil
		end
		dirIn, dirOut = dirIn.Unit, dirOut.Unit
		local a2 = Vector2.new(dirIn.X, dirIn.Z)
		local b2 = Vector2.new(dirOut.X, dirOut.Z)
		local cross = a2.X * b2.Y - a2.Y * b2.X
		if math.abs(cross) <= 0.2 then
			return nil
		end
		local w = Vector2.new(p2.X - p0.X, p2.Z - p0.Z)
		local t = (w.X * b2.Y - w.Y * b2.X) / cross -- along the way in
		local u = (a2.X * w.Y - a2.Y * w.X) / cross -- back from p2 along the way out
		local fits = if strict then t >= 6 and u >= 6 and math.min(t, u) >= 0.3 * math.max(t, u) else t > 1 and u > 1
		if fits and t < d * 1.2 and u < d * 1.2 then
			local c = p0 + dirIn * t
			return Vector3.new(c.X, (p0.Y + p2.Y) / 2, c.Z)
		end
		return nil
	end
	-- (owner, 2026-11-04: "the cars are bugging here", a pile-up where Bay Link meets the Coast Road)
	-- a lane redrawn by hand with more or fewer points kept its junction links on the old last point,
	-- so its real last piece led nowhere (6 lanes). A link from past a lane's end, or from its last
	-- three points when nothing leaves the end itself, now starts at the end.
	local endLinked = {}
	for _, link in dataLinks do
		local l = dataLanes[link[1]]
		if l and link[2] == #l.pts // 3 then
			endLinked[link[1]] = true
		end
	end
	-- (21 Nov) a 1:1 Yangon lane nothing turns into (an inner lane of a wide road: the generator links junctions to
	-- one or two lanes only) took its cars nowhere and was never used: it gets the links into its neighbour lane
	-- (same road and way, starting within 20 studs), so junction traffic spreads over every lane
	do
		local intoLane = {}
		for _, link in dataLinks do
			if link[1] ~= link[3] then
				intoLane[link[3]] = intoLane[link[3]] or {}
				table.insert(intoLane[link[3]], link)
			end
		end
		local function startOf(l): Vector3
			return Vector3.new(l.pts[1], l.pts[2], l.pts[3])
		end
		local extra = {}
		for li, l in dataLanes do
			if l.yangon and not l.closed and not l.skip and not intoLane[li] and #l.pts >= 6 then
				for _, d in { -1, 1, -2, 2 } do
					local sib = dataLanes[li + d]
					if sib and sib.road == l.road and sib.way == l.way and intoLane[li + d] and (startOf(sib) - startOf(l)).Magnitude < 20 then
						for _, link in intoLane[li + d] do
							if link[1] ~= li then
								table.insert(extra, { link[1], link[2], li, link[4] })
							end
						end
						break
					end
				end
			end
		end
		for _, x in extra do
			table.insert(dataLinks, x)
		end
	end
	local made = {} -- [piece][piece] = true: one turn per pair (two links can pick the same pair)
	for _, link in dataLinks do
		local fromLane, fromK, toLane, toK = link[1], link[2], link[3], link[4]
		local fl = dataLanes[fromLane]
		local fromN = if fl then #fl.pts // 3 else 0
		if fl and not fl.closed and (fromK > fromN or (not endLinked[fromLane] and fromK >= fromN - 3)) then
			fromK = fromN
		end
		local fromRow, toRow = pieces[fromLane], pieces[toLane]
		-- (21 Nov) a link INTO a lane's last point (a roundabout lane closed by its own last -> first link,
		-- e.g. Maha Bandula Road #3 into Roundabout 4) found no piece starting there and was dropped, so
		-- whole roads behind it led nowhere and were pruned (1,972 1:1 pieces): join its last piece instead
		local tlN = if dataLanes[toLane] then #dataLanes[toLane].pts // 3 else 0
		if toK >= tlN and tlN >= 2 and not (fromLane == toLane and toK == 1) then
			toK = tlN - 1
		end
		-- (21 Nov) a link FROM a lane's first point (a roundabout's lane-to-lane hops, a side road leaving at a
		-- road's very start) had no piece ending there and was dropped: on a closed lane point 1 is also its
		-- last point (the last piece ends there), on an open one leave from its first piece
		if fromRow and fromK <= 1 then
			fromK = if fl and fl.closed then #fromRow + 1 else 2
		end
		local before = fromRow and fromRow[fromK - 1] -- the piece ending at point fromK
		local after = toRow and toRow[toK] -- the piece starting at point toK
		if before and after then
			if fromLane == toLane and toK == 1 then
				-- a loop closing on itself: straight on
				table.insert(before.next, after)
			else
				local b, a, p1 = before, after, nil
				-- (a lane change on the same road goes straight across, no corner to find)
				local tl = dataLanes[toLane]
				local laneChange = tl ~= nil and fl.road == tl.road and fl.way == tl.way
				-- (2026-11-04) a pick made in Studio by tools/riviera/TurnPicks.luau: the pieces back
				-- and on whose arc stays on the road (the nearest arc cut over a kerb at 23 corners)
				local key = fromLane .. ":" .. fromK .. ">" .. toLane .. ":" .. toK
				local pick = turnPicks[key]
				if pick and not laneChange then
					local bb, aa = fromRow[fromK - 1 - pick[1]], toRow[toK + pick[2]]
					local c = if bb and aa then corner(bb, aa) else nil
					if c then
						b, a, p1 = bb, aa, c
					end
				end
				for pass = if STRICT_TURNS then 1 else 2, if laneChange or p1 then 0 else 2 do
					local strict = pass == 1
					local best = math.huge
					for back = 0, if strict then 3 else 2 do
						for ahead = 0, if strict then 5 else 3 do
							local bb, aa = fromRow[fromK - 1 - back], toRow[toK + ahead]
							if bb and aa and back + ahead < best then
								local c = corner(bb, aa, strict)
								if c then
									b, a, p1, best = bb, aa, c, back + ahead
								end
							end
						end
					end
					if p1 then
						break
					end
				end
				if not p1 then
					-- straight on or turning back: the old way
					local d = (after.p0 - before.p2).Magnitude
					p1 = before.p2 + (before.p2 - before.p0).Unit * math.min(d * 0.5, 30)
				end
				made[b] = made[b] or {}
				if not made[b][a] then
					made[b][a] = true
					local turn = newSegment(all, b.p2, p1 :: Vector3, a.p0, "turn")
					turn.speedK = 0.8
					turn.turnSpeed = 18
					turn.next = { a }
					turn.route = a.route -- (a turn onto a route counts as the route)
					turn.rivHighway = a.rivHighway
					-- a lane change (way in and way out within 30 degrees): no slowing for it, and it
					-- weighs like going straight on
					local dIn = (b.p2 - b.p0) * Vector3.new(1, 0, 1)
					local dOut = (a.p2 - a.p0) * Vector3.new(1, 0, 1)
					if dIn.Magnitude > 0.1 and dOut.Magnitude > 0.1 and dIn.Unit:Dot(dOut.Unit) > math.cos(math.rad(30)) then
						turn.turning = false
						turn.laneChange = true -- (Traffic: it gives way to cars in the lane it moves into)
						turn.turnSpeed = nil
						turn.speedK = 1
						turn.dir = 1
					end
					table.insert(b.next, turn)
				end
			end
		end
	end
	-- (same day) a turn that leaves a piece or two early (the clean arcs above) left the lane's last
	-- pieces leading nowhere when nothing else left from there (20 places): a car going straight on
	-- drove into the dead end and the queue behind it piled up. Pieces and turns with no way on are
	-- taken out of the graph (step by step back from each dead end), so every choice goes somewhere.
	-- (21 Nov, "make the loading screen load fast") walked back from each dead end through a list of who leads into
	-- what: the old repeat-until-nothing-changes sweep took 320 passes over the 1:1 lanes (3.5 s of a 3.7 s build on a
	-- PC, at the start of every client and in Chauffeur.init); same result
	-- (21 Nov) on a short lane (2-4 pieces) the turn in can join a piece or two AFTER the piece the turn out
	-- leaves from (each turn picks its own clean arc), so a car coming in met a dead end and whole roads
	-- behind it were pruned (Zoological Garden Road into Roundabout 1). A lane's last piece with no way on
	-- gets its own turns to wherever the nearest piece up to 3 back turns off to.
	for li, row in pieces do
		local l = dataLanes[li]
		local last = row[#row]
		if l and not l.closed and last and #last.next == 0 then
			for back = 1, math.min(3, #row - 1) do
				local prev = row[#row - back]
				local outs = {}
				for _, t in prev.next do
					if t ~= row[#row - back + 1] and t.next and t.next[1] then
						table.insert(outs, t.next[1])
					end
				end
				if #outs > 0 then
					for _, a in outs do
						local mid = (last.p2 + a.p0) / 2
						local turn = newSegment(all, last.p2, mid, a.p0, "turn")
						turn.speedK = 0.8
						turn.turnSpeed = 18
						turn.next = { a }
						turn.route = a.route
						turn.rivHighway = a.rivHighway
						table.insert(last.next, turn)
					end
					break
				end
			end
		end
	end
	local dead = {}
	local into = {} -- [seg] = the pieces and turns whose next holds it
	local stack = {}
	for _, seg in all do
		for _, nx in seg.next do
			local list = into[nx]
			if list then
				table.insert(list, seg)
			else
				into[nx] = { seg }
			end
		end
		if #seg.next == 0 then
			dead[seg] = true
			table.insert(stack, seg)
		end
	end
	local function prune()
		while #stack > 0 do
			local gone = table.remove(stack)
			for _, seg in into[gone] or {} do
				if not dead[seg] then
					for i = #seg.next, 1, -1 do
						if dead[seg.next[i]] then
							table.remove(seg.next, i)
						end
					end
					if #seg.next == 0 then
						dead[seg] = true
						table.insert(stack, seg)
					end
				end
			end
		end
	end
	prune()
	-- (21 Nov) traps: a part of the network cars can drive into but never leave (5 small roundabouts with no roads
	-- joined, U-turn loops at the edge of the built districts: San Da Koo Street, Bo Min Yaung / Yarza Thingyan
	-- Road). Every small part (under 1,000 pieces) with no way out is taken out like a dead end, so cars don't pile up there.
	do
		local index, low, onStack, sstack, idx = {}, {}, {}, {}, 0
		local comps = {}
		for _, v0 in all do
			if dead[v0] or index[v0] then
				continue
			end
			local work = { { v0, 1 } }
			index[v0], low[v0] = idx, idx
			idx += 1
			table.insert(sstack, v0)
			onStack[v0] = true
			while #work > 0 do
				local top = work[#work]
				local v, i = top[1], top[2]
				local nx = v.next[i]
				if nx then
					top[2] = i + 1
					if not dead[nx] then
						if index[nx] == nil then
							index[nx], low[nx] = idx, idx
							idx += 1
							table.insert(sstack, nx)
							onStack[nx] = true
							table.insert(work, { nx, 1 })
						elseif onStack[nx] then
							low[v] = math.min(low[v], index[nx])
						end
					end
				else
					table.remove(work)
					if #work > 0 then
						local u = work[#work][1]
						low[u] = math.min(low[u], low[v])
					end
					if low[v] == index[v] then
						local members = {}
						while true do
							local w = table.remove(sstack)
							onStack[w] = nil
							table.insert(members, w)
							if w == v then
								break
							end
						end
						table.insert(comps, members)
					end
				end
			end
		end
		local biggest, compOf = nil, {}
		for k, m in comps do
			for _, s in m do
				compOf[s] = k
			end
			if biggest == nil or #m > #comps[biggest] then
				biggest = k
			end
		end
		-- (only small ones: each map's network is its own big part, the old maps' and the 1:1 Yangon's)
		for k, m in comps do
			if k ~= biggest and #m < 1000 then
				local leaves = false
				for _, s in m do
					for _, nx in s.next do
						if not dead[nx] and compOf[nx] ~= k then
							leaves = true
							break
						end
					end
					if leaves then
						break
					end
				end
				if not leaves then
					for _, s in m do
						dead[s] = true
						table.insert(stack, s)
					end
				end
			end
		end
		prune()
	end
	-- (owner, 2026-11-21: "put traffic lights too") traffic lights at the 1:1 Yangon's junctions. A junction is a
	-- cluster of link mouths (where a link leaves or joins a lane) with 2+ roads, 3+ lanes and no roundabout; the lane
	-- piece that enters it (ends inside, starts outside) gets the old city's signal (seg.signal, i = junction, axis by
	-- heading), so Traffic / Chauffeur / Police stop there on red exactly like the old city. A cluster where every
	-- approach runs the same way (a road changing name, a merge) gets no lights. `signals` is for YangonSignals (poles).
	local signals = {}
	do
		local CELL = 60
		local function baseRoad(name: string?): string
			return (string.gsub(name or "", "%s*#%d+$", ""))
		end
		local function lanePoint(l, k: number): Vector3
			local p = l.pts
			return Vector3.new(p[3 * k - 2], p[3 * k - 1], p[3 * k])
		end
		local function flat(v: Vector3): Vector3
			return Vector3.new(v.X, 0, v.Z)
		end
		local mouths = {}
		for _, link in dataLinks do
			local fl, tl = dataLanes[link[1]], dataLanes[link[3]]
			if fl and tl and fl.yangon and tl.yangon and link[1] ~= link[3] and not fl.skip and not tl.skip then
				local round = fl.closed or tl.closed or string.find(fl.road or "", "Roundabout", 1, true) ~= nil or string.find(tl.road or "", "Roundabout", 1, true) ~= nil
				local fk = math.clamp(link[2], 1, #fl.pts // 3)
				local tk = math.clamp(link[4], 1, #tl.pts // 3)
				table.insert(mouths, { pos = lanePoint(fl, fk), road = baseRoad(fl.road), lane = link[1], round = round })
				table.insert(mouths, { pos = lanePoint(tl, tk), road = baseRoad(tl.road), lane = link[3], round = round })
			end
		end
		-- cluster the mouths (union-find over a grid, 40 studs)
		local up = {}
		local function find(a: number): number
			while up[a] ~= a do
				up[a] = up[up[a]]
				a = up[a]
			end
			return a
		end
		local grid = {}
		for k, m in mouths do
			up[k] = k
			local cx, cz = math.floor(m.pos.X / CELL), math.floor(m.pos.Z / CELL)
			for dx = -1, 1 do
				for dz = -1, 1 do
					for _, o in grid[(cx + dx) .. "," .. (cz + dz)] or {} do
						local q = mouths[o].pos
						if (q - m.pos).Magnitude < 40 then
							local ra, rb = find(k), find(o)
							if ra ~= rb then
								up[math.max(ra, rb)] = math.min(ra, rb)
							end
						end
					end
				end
			end
			local key = cx .. "," .. cz
			grid[key] = grid[key] or {}
			table.insert(grid[key], k)
		end
		local order, groups = {}, {}
		for k in mouths do
			local r = find(k)
			if not groups[r] then
				groups[r] = {}
				table.insert(order, r)
			end
			table.insert(groups[r], mouths[k])
		end
		-- the Yangon lane pieces by where they end (for the entering-piece search)
		local pieceGrid = {}
		for li, l in dataLanes do
			if l.yangon and not l.skip then
				for _, seg in pieces[li] do
					local key = math.floor(seg.p2.X / CELL) .. "," .. math.floor(seg.p2.Z / CELL)
					pieceGrid[key] = pieceGrid[key] or {}
					table.insert(pieceGrid[key], seg)
				end
			end
		end
		local junction = 0
		for _, r in order do
			local g = groups[r]
			local roads, lanesIn, nRoads, nLanes, round = {}, {}, 0, 0, false
			local sum = Vector3.zero
			for _, m in g do
				round = round or m.round
				if not roads[m.road] then
					roads[m.road] = true
					nRoads += 1
				end
				if not lanesIn[m.lane] then
					lanesIn[m.lane] = true
					nLanes += 1
				end
				sum += m.pos
			end
			if round or nRoads < 2 or nLanes < 3 then
				continue
			end
			local c = sum / #g
			local radius = 0
			local tall = false
			for _, m in g do
				radius = math.max(radius, (flat(m.pos) - flat(c)).Magnitude)
				tall = tall or math.abs(m.pos.Y - c.Y) > 6
			end
			if tall then
				continue -- (a flyover over a road: two levels, no junction)
			end
			radius = math.clamp(radius + 6, 18, 70)
			local entering = {}
			local cx, cz = math.floor(c.X / CELL), math.floor(c.Z / CELL)
			local reach = math.ceil((radius + 30) / CELL)
			for dx = -reach, reach do
				for dz = -reach, reach do
					for _, seg in pieceGrid[(cx + dx) .. "," .. (cz + dz)] or {} do
						if not seg.signal and (flat(seg.p2) - flat(c)).Magnitude < radius and (flat(seg.p0) - flat(c)).Magnitude >= radius and math.abs(seg.p2.Y - c.Y) < 6 then
							table.insert(entering, seg)
						end
					end
				end
			end
			if #entering < 2 then
				continue
			end
			table.sort(entering, function(a, b)
				return a.id < b.id
			end)
			local ref = flat(entering[1].p2 - entering[1].p0).Unit
			local axes, hasZ = {}, false
			for k, seg in entering do
				local h = flat(seg.p2 - seg.p0).Unit
				axes[k] = if math.abs(h:Dot(ref)) >= 0.7071 then "X" else "Z"
				hasZ = hasZ or axes[k] == "Z"
			end
			if not hasZ then
				continue -- (every approach runs the same way: no cross traffic)
			end
			junction += 1
			for k, seg in entering do
				seg.signal, seg.i, seg.j, seg.axis = true, junction, 0, axes[k]
				table.insert(signals, { pos = seg.p2, dir = flat(seg.p2 - seg.p0).Unit, axis = axes[k], i = junction, center = c, radius = radius })
			end
		end
	end
	local live = {}
	for _, seg in lanes do
		if not dead[seg] then
			table.insert(live, seg)
		end
	end
	-- ids continue after the old city's (CityLayout.buildGraph().all), so one list holds both
	-- (the chauffeur sends segments by id: ChauffeurRoute.graph().all[id])
	local base = #CityLayout.buildGraph().all
	for i, seg in all do
		seg.id = base + i
	end
	-- (rows, links and corner are for the Studio tools: TurnPicks)
	cached = { lanes = live, all = all, dead = dead, rows = pieces, links = dataLinks, corner = corner, lanesData = dataLanes, endLinked = endLinked, signals = signals }
	return cached
end

-- (car resets, 2026-11-04: Backspace put the car back on the old city's lanes, out in the sea west
-- of Monaco) the nearest point on a Riviera lane and the way it runs, or nil without lane data
function RivieraTraffic.nearestCFrame(pos: Vector3): CFrame?
	local g = RivieraTraffic.build()
	if not g then
		return nil
	end
	local best: CFrame? = nil
	local bd = math.huge
	for _, seg in g.lanes do
		local sg = seg :: any
		if (sg.p1 - pos).Magnitude < sg.length + bd then
			local n = math.max(2, math.ceil(sg.length / 3))
			for k = 0, n do
				local p, dir = CityLayout.sample(seg, sg.length * k / n)
				local d = (p - pos).Magnitude
				if d < bd then
					bd = d
					local flat = Vector3.new(dir.X, 0, dir.Z)
					best = if flat.Magnitude > 0.01 then CFrame.lookAt(p, p + flat.Unit) else CFrame.new(p)
				end
			end
		end
	end
	return best
end

return RivieraTraffic

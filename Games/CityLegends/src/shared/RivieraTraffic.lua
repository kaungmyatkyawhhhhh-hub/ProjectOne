--[[
	RivieraTraffic (shared): the Riviera's lane graph for the NPC traffic (owner 2026-11-02:
	"traffic on the new map (reduce traffic)").

	Built from RivieraLanes (generated by tools/map_plan/export_lanes.py): every road 2 lanes each way (the streets 1, Config.Traffic.StreetLanes),
	a piece per ~24 studs, turns where roads meet, U-turns at dead ends, loops wrap round. The pieces
	are CityLayout segments (same fields, so Traffic drives them like the old city's): no lights
	(signal off), dir 1 on lanes and 2 on turns (cars slow before a turn, prefer going straight),
	riviera = true (Traffic keeps few cars here: Config.Traffic.RivieraMax).

	RivieraTraffic.build() -> { lanes: { Segment } (the ones with a way on), all: { Segment }, dead } (cached), or nil without data
]]

local CityLayout = require(script.Parent:WaitForChild("CityLayout"))
local Config = require(script.Parent:WaitForChild("Config"))

local RivieraTraffic = {}

local STRICT_TURNS = false -- (the balanced-arc search below; off: it made more turns cut over kerbs)
local SAMPLES = 12 -- as CityLayout's (CityLayout.sample walks seg.samples)

local function bezier(p0: Vector3, p1: Vector3, p2: Vector3, t: number): Vector3
	local u = 1 - t
	return p0 * (u * u) + p1 * (2 * u * t) + p2 * (t * t)
end

local function newSegment(list, p0: Vector3, p1: Vector3, p2: Vector3, kind: string): CityLayout.Segment
	local samples = { 0 }
	local total = 0
	local prev = p0
	for k = 1, SAMPLES do
		local pt = bezier(p0, p1, p2, k / SAMPLES)
		total += (pt - prev).Magnitude
		samples[k + 1] = total
		prev = pt
	end
	local seg = {
		id = #list + 1,
		p0 = p0,
		p1 = p1,
		p2 = p2,
		length = math.max(total, 0.01),
		kind = kind,
		i = 0,
		j = 0,
		axis = "X",
		dir = if kind == "turn" then 2 else 1,
		lane = 1,
		turning = kind == "turn",
		signal = false,
		speedK = 1,
		next = {},
		samples = samples,
		riviera = true,
	}
	table.insert(list, seg)
	return seg :: any
end

-- (owner, 2026-11-04: "Make the road 1+1 for the roads which isnt yellow. The yellow road will stay
-- the same") the streets (every road but the three yellow routes) have one lane each way: lane 1
-- runs in the middle of its half (halfway to the old lane 2, so 16 out on a full-width road), lane 2
-- is dropped, and junction links onto or off a lane 2 use its lane 1. Returns the lanes (a dropped
-- one is marked skip) and the links, both in the data's numbering.
local function oneLaneStreets(data): ({ any }, { { number } })
	if (Config.Traffic :: any).StreetLanes ~= 1 then
		return data.lanes, data.links
	end
	local first = {}
	for li, l in data.lanes do
		if l.kind ~= "route" and l.lane == 1 then
			first[l.road .. "|" .. l.way] = li
		end
	end
	local partner = {} -- [a street's lane 2] = its lane 1 (same road, same way)
	for li, l in data.lanes do
		if l.kind ~= "route" and l.lane == 2 then
			partner[li] = first[l.road .. "|" .. l.way]
		end
	end
	local lanes = table.clone(data.lanes)
	local function count(li: number): number
		return #data.lanes[li].pts // 3
	end
	for l2, l1 in partner do
		local a, b = data.lanes[l1].pts, data.lanes[l2].pts
		local na, nb = #a // 3, #b // 3
		local pts = table.create(#a)
		for k = 1, na do
			local p = Vector3.new(a[3 * k - 2], a[3 * k - 1], a[3 * k])
			-- the nearest point on lane 2, near the same point number (hand-moved lanes can be a
			-- point or two out; a hairpin's other leg is never that close in number)
			local best, bq = math.huge, nil
			for j = math.max(1, k - 3), math.min(nb - 1, k + 3) do
				local q0 = Vector3.new(b[3 * j - 2], b[3 * j - 1], b[3 * j])
				local q1 = Vector3.new(b[3 * j + 1], b[3 * j + 2], b[3 * j + 3])
				local d = q1 - q0
				local t = if d:Dot(d) > 0.0001 then math.clamp((p - q0):Dot(d) / d:Dot(d), 0, 1) else 0
				local q = q0 + d * t
				if (q - p).Magnitude < best then
					best, bq = (q - p).Magnitude, q
				end
			end
			local m = if bq and best < 26 then (p + bq) / 2 else p
			pts[3 * k - 2], pts[3 * k - 1], pts[3 * k] = m.X, m.Y, m.Z
		end
		local one = table.clone(data.lanes[l1])
		one.pts = pts
		lanes[l1] = one
		local two = table.clone(data.lanes[l2])
		two.skip = true
		lanes[l2] = two
	end
	local links, seen = {}, {}
	for _, link in data.links do
		local a, ka, b, kb = link[1], link[2], link[3], link[4]
		local pa, pb = partner[a], partner[b]
		if pa then
			ka = if ka >= count(a) then count(pa) else math.clamp(ka, 2, count(pa))
			a = pa
		end
		if pb then
			kb = math.clamp(kb, 1, count(pb) - 1)
			b = pb
		end
		local key = a .. ":" .. ka .. ":" .. b .. ":" .. kb
		if not seen[key] then
			seen[key] = true
			table.insert(links, { a, ka, b, kb })
		end
	end
	return lanes, links
end

-- (owner, 2026-11-04: "there is a traffic problem here, its because they dont know how to turn
-- properly", the Mountain Road's west end) where a yellow route ends into a street, which is now one
-- lane each way, both its lanes turned into that one lane at the very end and cut across each
-- other there. Now the outer lane merges into the inner one ~200 studs before the end (a lane
-- change), and only the inner lane turns. The same at a route's start: a street that fed both its
-- lanes through two tight turns feeds the inner one, and cars change into the outer lane a little
-- further on. And one turn per lane end and lane it turns into (two links had made a sharp one and
-- a gentle one side by side; the gentle one, joining later, stays).
local function mergeRouteEnds(lanes: { any }, links: { { number } }): { { number } }
	local function n(li: number): number
		return #lanes[li].pts // 3
	end
	local inner = {}
	for li, l in lanes do
		if l.kind == "route" and l.lane == 1 and not l.skip then
			inner[l.road .. "|" .. l.way] = li
		end
	end
	local endTargets = {} -- [lane] = the lanes its last two points turn into
	for _, link in links do
		if link[2] >= n(link[1]) - 1 then
			endTargets[link[1]] = endTargets[link[1]] or {}
			endTargets[link[1]][link[3]] = true
		end
	end
	local merged = {}
	for li, l in lanes do
		if l.kind == "route" and l.lane == 2 and not l.closed and not l.skip then
			local l1 = inner[l.road .. "|" .. l.way]
			local mine, theirs = endTargets[li], if l1 then endTargets[l1] else nil
			if mine and theirs and n(li) > 14 and n(l1) > 14 then
				local same = true
				for t in mine do
					if not theirs[t] then
						same = false
					end
				end
				if same then
					merged[li] = l1
				end
			end
		end
	end
	-- the start: route lane 2s fed only from lanes that feed lane 1 too
	local startFrom = {} -- [lane] = the lanes turning into its first two points
	for _, link in links do
		if link[4] <= 2 and link[1] ~= link[3] then
			startFrom[link[3]] = startFrom[link[3]] or {}
			startFrom[link[3]][link[1]] = true
		end
	end
	local split = {}
	for li, l in lanes do
		if l.kind == "route" and l.lane == 2 and not l.closed and not l.skip then
			local l1 = inner[l.road .. "|" .. l.way]
			local mine, theirs = startFrom[li], if l1 then startFrom[l1] else nil
			if mine and theirs and n(li) > 14 and n(l1) > 14 then
				local same = true
				for f in mine do
					if not theirs[f] then
						same = false
					end
				end
				if same then
					split[li] = l1
				end
			end
		end
	end
	local out = {}
	local endBest = {} -- ["from>to"] = the end link kept (the one joining furthest on)
	for _, link in links do
		local from, to = link[1], link[3]
		if merged[from] and link[2] >= n(from) - 1 then
			continue
		end
		if split[to] and link[4] <= 2 and from ~= to then
			continue
		end
		if link[2] >= n(from) - 1 and from ~= to then
			local key = from .. ">" .. to
			local had = endBest[key]
			if had then
				if link[4] > had[4] then
					had[2], had[4] = link[2], link[4]
				end
				continue
			end
			local copy = { link[1], link[2], link[3], link[4] }
			endBest[key] = copy
			table.insert(out, copy)
		else
			table.insert(out, link)
		end
	end
	for l2, l1 in merged do
		local k2 = n(l2) - 9
		table.insert(out, { l2, k2, l1, math.min(k2 + 3, n(l1) - 6) })
	end
	for l2, l1 in split do
		table.insert(out, { l1, 4, l2, 7 })
	end
	return out
end

-- turn picks from tools/riviera/TurnPicks.luau (["fromLane:fromK>toLane:toK"] = { back, ahead })
local turnPicks: { [string]: { number } } = {}
do
	local m = script.Parent:FindFirstChild("RivieraTurnPicks")
	if m then
		local ok, t = pcall(require, m)
		if ok and type(t) == "table" then
			turnPicks = t
		end
	end
end

local cached = nil
function RivieraTraffic.build()
	if cached then
		return cached
	end
	local ok, data = pcall(function()
		return require(script.Parent:WaitForChild("RivieraLanes", 5))
	end)
	if not ok or type(data) ~= "table" then
		return nil
	end
	-- (2026-11-04) the Riviera Highway's and the Summit Pass's lanes live in their own module (Studio
	-- refuses a script over 200,000 characters): numbered on from RivieraLanes', added to its lists
	local okH, extra = pcall(function()
		return require(script.Parent:WaitForChild("RivieraLanesHighway", 2))
	end)
	if okH and type(extra) == "table" and extra.first == #data.lanes + 1 then
		local lanesAll, linksAll = table.clone(data.lanes), table.clone(data.links)
		for _, l in extra.lanes do
			table.insert(lanesAll, l)
		end
		for _, k in extra.links do
			table.insert(linksAll, k)
		end
		data = { lanes = lanesAll, links = linksAll }
	end
	local dataLanes, dataLinks = oneLaneStreets(data)
	dataLinks = mergeRouteEnds(dataLanes, dataLinks)
	local all, lanes = {}, {}
	local pieces = {} -- [laneIndex][pointIndex] = the piece starting at that point
	for li, l in dataLanes do
		local pts = l.pts
		local n = #pts // 3
		local row = {}
		pieces[li] = row
		if l.skip then
			continue -- (a street's dropped lane 2)
		end
		-- (the main routes run a little faster than the town streets, never highway pace)
		local speedK = if l.kind == "route" then 1 else 0.85
		for k = 1, n - 1 do
			local a = Vector3.new(pts[3 * k - 2], pts[3 * k - 1], pts[3 * k])
			local b = Vector3.new(pts[3 * k + 1], pts[3 * k + 2], pts[3 * k + 3])
			local seg = newSegment(all, a, (a + b) / 2, b, "lane")
			seg.lane = l.lane
			seg.road = l.road -- (the server's start spots use it)
			seg.route = l.kind == "route" -- the three long routes (yellow on the map)
			seg.rivHighway = l.highway == true -- the Riviera Highway (Traffic keeps few cars on it)
			seg.speedK = speedK
			row[k] = seg
			table.insert(lanes, seg)
			if k > 1 then
				table.insert(row[k - 1].next, seg)
			end
		end
	end
	-- turns between lanes: a curve from the end of one piece to the start of another
	-- (owner, 2026-11-03: "some cars are turning left and turning right, they're not programmed
	-- properly"): where a lane's end and the next lane's start sit too close for the angle, the curve
	-- had to swing one way and then back (89 of 414 turns turned both ways). Now the turn may leave a
	-- piece or two earlier and join a piece or two later, picking the nearest pair whose way in and
	-- way out meet ahead of both: one clean arc
	-- (2026-11-04, "they dont know how to turn properly") first a strict search, wider (up to 3 pieces
	-- back and 5 on): the arc must be balanced, its corner at least 6 studs from both ends and neither
	-- leg under 0.3 of the other (a lopsided arc ran straight and then snapped round in its last
	-- studs); only if none fits, the loose search as before
	local function corner(before, after, strict: boolean?): Vector3?
		local p0, p2 = before.p2, after.p0
		local d = (p2 - p0).Magnitude
		local dirIn = (before.p2 - before.p0) * Vector3.new(1, 0, 1)
		local dirOut = (after.p2 - after.p0) * Vector3.new(1, 0, 1)
		if dirIn.Magnitude < 0.1 or dirOut.Magnitude < 0.1 then
			return nil
		end
		dirIn, dirOut = dirIn.Unit, dirOut.Unit
		local a2 = Vector2.new(dirIn.X, dirIn.Z)
		local b2 = Vector2.new(dirOut.X, dirOut.Z)
		local cross = a2.X * b2.Y - a2.Y * b2.X
		if math.abs(cross) <= 0.2 then
			return nil
		end
		local w = Vector2.new(p2.X - p0.X, p2.Z - p0.Z)
		local t = (w.X * b2.Y - w.Y * b2.X) / cross -- along the way in
		local u = (a2.X * w.Y - a2.Y * w.X) / cross -- back from p2 along the way out
		local fits = if strict then t >= 6 and u >= 6 and math.min(t, u) >= 0.3 * math.max(t, u) else t > 1 and u > 1
		if fits and t < d * 1.2 and u < d * 1.2 then
			local c = p0 + dirIn * t
			return Vector3.new(c.X, (p0.Y + p2.Y) / 2, c.Z)
		end
		return nil
	end
	-- (owner, 2026-11-04: "the cars are bugging here", a pile-up where Bay Link meets the Coast Road)
	-- a lane redrawn by hand with more or fewer points kept its junction links on the old last point,
	-- so its real last piece led nowhere (6 lanes). A link from past a lane's end, or from its last
	-- three points when nothing leaves the end itself, now starts at the end.
	local endLinked = {}
	for _, link in dataLinks do
		local l = dataLanes[link[1]]
		if l and link[2] == #l.pts // 3 then
			endLinked[link[1]] = true
		end
	end
	local made = {} -- [piece][piece] = true: one turn per pair (two links can pick the same pair)
	for _, link in dataLinks do
		local fromLane, fromK, toLane, toK = link[1], link[2], link[3], link[4]
		local fl = dataLanes[fromLane]
		local fromN = if fl then #fl.pts // 3 else 0
		if fl and not fl.closed and (fromK > fromN or (not endLinked[fromLane] and fromK >= fromN - 3)) then
			fromK = fromN
		end
		local fromRow, toRow = pieces[fromLane], pieces[toLane]
		local before = fromRow and fromRow[fromK - 1] -- the piece ending at point fromK
		local after = toRow and toRow[toK] -- the piece starting at point toK
		if before and after then
			if fromLane == toLane and toK == 1 then
				-- a loop closing on itself: straight on
				table.insert(before.next, after)
			else
				local b, a, p1 = before, after, nil
				-- (a lane change on the same road goes straight across, no corner to find)
				local tl = dataLanes[toLane]
				local laneChange = tl ~= nil and fl.road == tl.road and fl.way == tl.way
				-- (2026-11-04) a pick made in Studio by tools/riviera/TurnPicks.luau: the pieces back
				-- and on whose arc stays on the road (the nearest arc cut over a kerb at 23 corners)
				local key = fromLane .. ":" .. fromK .. ">" .. toLane .. ":" .. toK
				local pick = turnPicks[key]
				if pick and not laneChange then
					local bb, aa = fromRow[fromK - 1 - pick[1]], toRow[toK + pick[2]]
					local c = if bb and aa then corner(bb, aa) else nil
					if c then
						b, a, p1 = bb, aa, c
					end
				end
				for pass = if STRICT_TURNS then 1 else 2, if laneChange or p1 then 0 else 2 do
					local strict = pass == 1
					local best = math.huge
					for back = 0, if strict then 3 else 2 do
						for ahead = 0, if strict then 5 else 3 do
							local bb, aa = fromRow[fromK - 1 - back], toRow[toK + ahead]
							if bb and aa and back + ahead < best then
								local c = corner(bb, aa, strict)
								if c then
									b, a, p1, best = bb, aa, c, back + ahead
								end
							end
						end
					end
					if p1 then
						break
					end
				end
				if not p1 then
					-- straight on or turning back: the old way
					local d = (after.p0 - before.p2).Magnitude
					p1 = before.p2 + (before.p2 - before.p0).Unit * math.min(d * 0.5, 30)
				end
				made[b] = made[b] or {}
				if not made[b][a] then
					made[b][a] = true
					local turn = newSegment(all, b.p2, p1 :: Vector3, a.p0, "turn")
					turn.speedK = 0.8
					turn.turnSpeed = 18
					turn.next = { a }
					turn.route = a.route -- (a turn onto a route counts as the route)
					turn.rivHighway = a.rivHighway
					-- a lane change (way in and way out within 30 degrees): no slowing for it, and it
					-- weighs like going straight on
					local dIn = (b.p2 - b.p0) * Vector3.new(1, 0, 1)
					local dOut = (a.p2 - a.p0) * Vector3.new(1, 0, 1)
					if dIn.Magnitude > 0.1 and dOut.Magnitude > 0.1 and dIn.Unit:Dot(dOut.Unit) > math.cos(math.rad(30)) then
						turn.turning = false
						turn.laneChange = true -- (Traffic: it gives way to cars in the lane it moves into)
						turn.turnSpeed = nil
						turn.speedK = 1
						turn.dir = 1
					end
					table.insert(b.next, turn)
				end
			end
		end
	end
	-- (same day) a turn that leaves a piece or two early (the clean arcs above) left the lane's last
	-- pieces leading nowhere when nothing else left from there (20 places): a car going straight on
	-- drove into the dead end and the queue behind it piled up. Pieces and turns with no way on are
	-- taken out of the graph (step by step back from each dead end), so every choice goes somewhere.
	local dead = {}
	local changed = true
	while changed do
		changed = false
		for _, seg in all do
			if not dead[seg] then
				for i = #seg.next, 1, -1 do
					if dead[seg.next[i]] then
						table.remove(seg.next, i)
					end
				end
				if #seg.next == 0 then
					dead[seg] = true
					changed = true
				end
			end
		end
	end
	local live = {}
	for _, seg in lanes do
		if not dead[seg] then
			table.insert(live, seg)
		end
	end
	-- ids continue after the old city's (CityLayout.buildGraph().all), so one list holds both
	-- (the chauffeur sends segments by id: ChauffeurRoute.graph().all[id])
	local base = #CityLayout.buildGraph().all
	for i, seg in all do
		seg.id = base + i
	end
	-- (rows, links and corner are for the Studio tools: TurnPicks)
	cached = { lanes = live, all = all, dead = dead, rows = pieces, links = dataLinks, corner = corner, lanesData = dataLanes, endLinked = endLinked }
	return cached
end

-- (car resets, 2026-11-04: Backspace put the car back on the old city's lanes, out in the sea west
-- of Monaco) the nearest point on a Riviera lane and the way it runs, or nil without lane data
function RivieraTraffic.nearestCFrame(pos: Vector3): CFrame?
	local g = RivieraTraffic.build()
	if not g then
		return nil
	end
	local best: CFrame? = nil
	local bd = math.huge
	for _, seg in g.lanes do
		local sg = seg :: any
		if (sg.p1 - pos).Magnitude < sg.length + bd then
			local n = math.max(2, math.ceil(sg.length / 3))
			for k = 0, n do
				local p, dir = CityLayout.sample(seg, sg.length * k / n)
				local d = (p - pos).Magnitude
				if d < bd then
					bd = d
					local flat = Vector3.new(dir.X, 0, dir.Z)
					best = if flat.Magnitude > 0.01 then CFrame.lookAt(p, p + flat.Unit) else CFrame.new(p)
				end
			end
		end
	end
	return best
end

return RivieraTraffic

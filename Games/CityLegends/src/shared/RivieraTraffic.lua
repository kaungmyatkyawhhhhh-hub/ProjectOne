--[[
	RivieraTraffic (shared): the Riviera's lane graph for the NPC traffic (owner 2026-11-02:
	"traffic on the new map (reduce traffic)").

	Built from RivieraLanes (generated by tools/map_plan/export_lanes.py): every road 2 lanes each way,
	a piece per ~24 studs, turns where roads meet, U-turns at dead ends, loops wrap round. The pieces
	are CityLayout segments (same fields, so Traffic drives them like the old city's): no lights
	(signal off), dir 1 on lanes and 2 on turns (cars slow before a turn, prefer going straight),
	riviera = true (Traffic keeps few cars here: Config.Traffic.RivieraMax).

	RivieraTraffic.build() -> { lanes: { Segment } (the ones with a way on), all: { Segment }, dead } (cached), or nil without data
]]

local CityLayout = require(script.Parent:WaitForChild("CityLayout"))

local RivieraTraffic = {}

local SAMPLES = 12 -- as CityLayout's (CityLayout.sample walks seg.samples)

local function bezier(p0: Vector3, p1: Vector3, p2: Vector3, t: number): Vector3
	local u = 1 - t
	return p0 * (u * u) + p1 * (2 * u * t) + p2 * (t * t)
end

local function newSegment(list, p0: Vector3, p1: Vector3, p2: Vector3, kind: string): CityLayout.Segment
	local samples = { 0 }
	local total = 0
	local prev = p0
	for k = 1, SAMPLES do
		local pt = bezier(p0, p1, p2, k / SAMPLES)
		total += (pt - prev).Magnitude
		samples[k + 1] = total
		prev = pt
	end
	local seg = {
		id = #list + 1,
		p0 = p0,
		p1 = p1,
		p2 = p2,
		length = math.max(total, 0.01),
		kind = kind,
		i = 0,
		j = 0,
		axis = "X",
		dir = if kind == "turn" then 2 else 1,
		lane = 1,
		turning = kind == "turn",
		signal = false,
		speedK = 1,
		next = {},
		samples = samples,
		riviera = true,
	}
	table.insert(list, seg)
	return seg :: any
end

local cached = nil
function RivieraTraffic.build()
	if cached then
		return cached
	end
	local ok, data = pcall(function()
		return require(script.Parent:WaitForChild("RivieraLanes", 5))
	end)
	if not ok or type(data) ~= "table" then
		return nil
	end
	local all, lanes = {}, {}
	local pieces = {} -- [laneIndex][pointIndex] = the piece starting at that point
	for li, l in data.lanes do
		local pts = l.pts
		local n = #pts // 3
		local row = {}
		pieces[li] = row
		-- (the main routes run a little faster than the town streets, never highway pace)
		local speedK = if l.kind == "route" then 1 else 0.85
		for k = 1, n - 1 do
			local a = Vector3.new(pts[3 * k - 2], pts[3 * k - 1], pts[3 * k])
			local b = Vector3.new(pts[3 * k + 1], pts[3 * k + 2], pts[3 * k + 3])
			local seg = newSegment(all, a, (a + b) / 2, b, "lane")
			seg.lane = l.lane
			seg.road = l.road -- (the server's start spots use it)
			seg.route = l.kind == "route" -- the three long routes (yellow on the map)
			seg.speedK = speedK
			row[k] = seg
			table.insert(lanes, seg)
			if k > 1 then
				table.insert(row[k - 1].next, seg)
			end
		end
	end
	-- turns between lanes: a curve from the end of one piece to the start of another
	-- (owner, 2026-11-03: "some cars are turning left and turning right, they're not programmed
	-- properly"): where a lane's end and the next lane's start sit too close for the angle, the curve
	-- had to swing one way and then back (89 of 414 turns turned both ways). Now the turn may leave a
	-- piece or two earlier and join a piece or two later, picking the nearest pair whose way in and
	-- way out meet ahead of both: one clean arc
	local function corner(before, after): Vector3?
		local p0, p2 = before.p2, after.p0
		local d = (p2 - p0).Magnitude
		local dirIn = (before.p2 - before.p0) * Vector3.new(1, 0, 1)
		local dirOut = (after.p2 - after.p0) * Vector3.new(1, 0, 1)
		if dirIn.Magnitude < 0.1 or dirOut.Magnitude < 0.1 then
			return nil
		end
		dirIn, dirOut = dirIn.Unit, dirOut.Unit
		local a2 = Vector2.new(dirIn.X, dirIn.Z)
		local b2 = Vector2.new(dirOut.X, dirOut.Z)
		local cross = a2.X * b2.Y - a2.Y * b2.X
		if math.abs(cross) <= 0.2 then
			return nil
		end
		local w = Vector2.new(p2.X - p0.X, p2.Z - p0.Z)
		local t = (w.X * b2.Y - w.Y * b2.X) / cross -- along the way in
		local u = (a2.X * w.Y - a2.Y * w.X) / cross -- back from p2 along the way out
		if t > 1 and u > 1 and t < d * 1.2 and u < d * 1.2 then
			local c = p0 + dirIn * t
			return Vector3.new(c.X, (p0.Y + p2.Y) / 2, c.Z)
		end
		return nil
	end
	-- (owner, 2026-11-04: "the cars are bugging here", a pile-up where Bay Link meets the Coast Road)
	-- a lane redrawn by hand with more or fewer points kept its junction links on the old last point,
	-- so its real last piece led nowhere (6 lanes). A link from past a lane's end, or from its last
	-- three points when nothing leaves the end itself, now starts at the end.
	local endLinked = {}
	for _, link in data.links do
		local l = data.lanes[link[1]]
		if l and link[2] == #l.pts // 3 then
			endLinked[link[1]] = true
		end
	end
	for _, link in data.links do
		local fromLane, fromK, toLane, toK = link[1], link[2], link[3], link[4]
		local fl = data.lanes[fromLane]
		local fromN = if fl then #fl.pts // 3 else 0
		if fl and not fl.closed and (fromK > fromN or (not endLinked[fromLane] and fromK >= fromN - 3)) then
			fromK = fromN
		end
		local fromRow, toRow = pieces[fromLane], pieces[toLane]
		local before = fromRow and fromRow[fromK - 1] -- the piece ending at point fromK
		local after = toRow and toRow[toK] -- the piece starting at point toK
		if before and after then
			if fromLane == toLane and toK == 1 then
				-- a loop closing on itself: straight on
				table.insert(before.next, after)
			else
				local b, a, p1 = before, after, nil
				local best = math.huge
				for back = 0, 2 do
					for ahead = 0, 3 do
						local bb, aa = fromRow[fromK - 1 - back], toRow[toK + ahead]
						if bb and aa and back + ahead < best then
							local c = corner(bb, aa)
							if c then
								b, a, p1, best = bb, aa, c, back + ahead
							end
						end
					end
				end
				if not p1 then
					-- straight on or turning back: the old way
					local d = (after.p0 - before.p2).Magnitude
					p1 = before.p2 + (before.p2 - before.p0).Unit * math.min(d * 0.5, 30)
				end
				local turn = newSegment(all, b.p2, p1 :: Vector3, a.p0, "turn")
				turn.speedK = 0.8
				turn.turnSpeed = 18
				turn.next = { a }
				turn.route = a.route -- (a turn onto a route counts as the route)
				table.insert(b.next, turn)
			end
		end
	end
	-- (same day) a turn that leaves a piece or two early (the clean arcs above) left the lane's last
	-- pieces leading nowhere when nothing else left from there (20 places): a car going straight on
	-- drove into the dead end and the queue behind it piled up. Pieces and turns with no way on are
	-- taken out of the graph (step by step back from each dead end), so every choice goes somewhere.
	local dead = {}
	local changed = true
	while changed do
		changed = false
		for _, seg in all do
			if not dead[seg] then
				for i = #seg.next, 1, -1 do
					if dead[seg.next[i]] then
						table.remove(seg.next, i)
					end
				end
				if #seg.next == 0 then
					dead[seg] = true
					changed = true
				end
			end
		end
	end
	local live = {}
	for _, seg in lanes do
		if not dead[seg] then
			table.insert(live, seg)
		end
	end
	-- ids continue after the old city's (CityLayout.buildGraph().all), so one list holds both
	-- (the chauffeur sends segments by id: ChauffeurRoute.graph().all[id])
	local base = #CityLayout.buildGraph().all
	for i, seg in all do
		seg.id = base + i
	end
	cached = { lanes = live, all = all, dead = dead }
	return cached
end

-- (car resets, 2026-11-04: Backspace put the car back on the old city's lanes, out in the sea west
-- of Monaco) the nearest point on a Riviera lane and the way it runs, or nil without lane data
function RivieraTraffic.nearestCFrame(pos: Vector3): CFrame?
	local g = RivieraTraffic.build()
	if not g then
		return nil
	end
	local best: CFrame? = nil
	local bd = math.huge
	for _, seg in g.lanes do
		local sg = seg :: any
		if (sg.p1 - pos).Magnitude < sg.length + bd then
			local n = math.max(2, math.ceil(sg.length / 3))
			for k = 0, n do
				local p, dir = CityLayout.sample(seg, sg.length * k / n)
				local d = (p - pos).Magnitude
				if d < bd then
					bd = d
					local flat = Vector3.new(dir.X, 0, dir.Z)
					best = if flat.Magnitude > 0.01 then CFrame.lookAt(p, p + flat.Unit) else CFrame.new(p)
				end
			end
		end
	end
	return best
end

return RivieraTraffic

"""Real OSM spots for YangonRoadside (2026-11-25): compound gates (barrier=gate: guard booths) and construction sites
(landuse=construction / building=construction: blue sheet hoarding), in 1:1 world studs.

    YANGON_SCALE=1to1 python tools/yangon/city/roadside_data.py   (from Games/CityLegends)
writes src/shared/YangonRoadsideData.lua.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import geo  # noqa: E402

assert geo.ONE_TO_ONE, "run with YANGON_SCALE=1to1"

pts = json.load(open(os.path.join(geo.BUILD, 'osm_ygn', 'points.json'), encoding='utf-8'))['points']
areas = json.load(open(os.path.join(geo.BUILD, 'osm_ygn', 'areas.json'), encoding='utf-8'))['areas']
blds = json.load(open(os.path.join(geo.BUILD, 'osm_ygn', 'buildings.json'), encoding='utf-8'))['buildings']

gates = []
for p in pts:
    if p.get('k') == 'barrier' and p.get('v') == 'gate':
        x, z = geo.world(*p['p'])
        gates.append(f"{x:.1f},{z:.1f}")

sites = []
for a in areas + blds:
    t = a.get('t', {})
    if t.get('landuse') == 'construction' or t.get('building') == 'construction':
        ring = [geo.world(*q) for q in a['p']]
        sites.append(";".join(f"{x:.1f},{z:.1f}" for x, z in ring))

out = os.path.join(os.path.dirname(__file__), '..', '..', '..', 'src', 'shared', 'YangonRoadsideData.lua')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write("-- generated by tools/yangon/city/roadside_data.py from the OSM extract (ODbL): do not edit\n")
    f.write("-- Gates: barrier=gate points \"x,z\" (1:1 world studs). Sites: landuse / building = construction rings.\n")
    f.write("return {\n")
    f.write('\tGates = "' + " ".join(gates) + '",\n')
    f.write("\tSites = {\n")
    for s in sites:
        f.write('\t\t"' + s + '",\n')
    f.write("\t},\n}\n")
print(len(gates), "gates,", len(sites), "sites ->", os.path.normpath(out))

"""peoples_park_osm.py (2026-11-28): People's Park's real layout from OSM (build/osm_ygn, ODbL) -> tools/yangon/PeoplesParkOSM.luau
(1:1 studs) for PeoplesPark.luau's P.grounds(): the park outline, lakes / ponds / fountains, footways and park drives,
car parks / pools / pitches / gardens as oriented boxes {x, z, length, width, angle}, mapped trees and gates.
Run from Games/CityLegends: python -X utf8 tools/yangon/city/peoples_park_osm.py"""
import json, math, os, sys
os.environ["YANGON_SCALE"] = "1to1"
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geo  # noqa: E402

PARK = 374243908
A = json.load(open("build/osm_ygn/areas.json", encoding="utf-8"))["areas"]
park = next(a for a in A if a["id"] == PARK)
P = [geo.world(*q) for q in park["p"]]


def inside(x, z, poly=P):
    c = False
    for i in range(len(poly)):
        x1, z1 = poly[i]
        x2, z2 = poly[i - 1]
        if (z1 > z) != (z2 > z) and x < (x2 - x1) * (z - z1) / (z2 - z1) + x1:
            c = not c
    return c


def obb(pts):
    """min-area oriented box {x, z, length, width, angle deg} (length along the angle)"""
    best = None
    for i in range(len(pts)):
        (x1, z1), (x2, z2) = pts[i - 1], pts[i]
        a = math.atan2(z2 - z1, x2 - x1)
        c, s = math.cos(a), math.sin(a)
        us = [x * c + z * s for x, z in pts]
        vs = [-x * s + z * c for x, z in pts]
        L, W = max(us) - min(us), max(vs) - min(vs)
        if best is None or L * W < best[0]:
            mu, mv = (max(us) + min(us)) / 2, (max(vs) + min(vs)) / 2
            best = (L * W, mu * c - mv * s, mu * s + mv * c, L, W, math.degrees(a))
    _, x, z, L, W, a = best
    if W > L:
        L, W, a = W, L, a + 90
    return [round(x, 1), round(z, 1), round(L, 1), round(W, 1), round(a, 1)]


def pl(pts):
    return "{" + ",".join("%d,%d" % (round(p[0]), round(p[1])) for p in pts) + "}"


out = {"water": [], "fount": [], "box": [], "ways": [], "trees": [], "gates": []}
for a in A:
    if a["id"] == PARK:
        continue
    xs = [geo.world(*q) for q in a["p"]]
    if xs[0] == xs[-1]:
        xs = xs[:-1]
    cx, cz = sum(x for x, _ in xs) / len(xs), sum(z for _, z in xs) / len(xs)
    if not inside(cx, cz):
        continue
    t = a["t"]
    if t.get("amenity") == "fountain":
        out["fount"].append(obb(xs) + [a["id"]])
    elif t.get("natural") == "water":
        out["water"].append((a["id"], t.get("water", "pond"), xs))
    else:
        kind = ("parking" if t.get("amenity") == "parking" else "pool" if t.get("leisure") == "swimming_pool" else
                "pitch" if t.get("leisure") == "pitch" else "garden" if t.get("leisure") == "garden" else
                "bridge" if t.get("man_made") == "bridge" else "grass" if t.get("landuse") == "grass" else None)
        if kind:
            out["box"].append((kind, obb(xs), a["id"]))
for f, k in (("roads", "roads"), ("lines", "lines")):
    for r in json.load(open("build/osm_ygn/%s.json" % f, encoding="utf-8"))[k]:
        hw = r["t"].get("highway")
        if hw not in ("footway", "path", "pedestrian", "steps", "service"):
            continue
        xs = [geo.world(*q) for q in r["p"]]
        if sum(inside(x, z) for x, z in xs) * 2 >= len(xs):
            out["ways"].append((hw, r["t"].get("bridge") == "yes", xs))
for p in json.load(open("build/osm_ygn/points.json", encoding="utf-8"))["points"]:
    x, z = geo.world(*p["p"])
    if inside(x, z):
        if p["k"] == "natural" and p["v"] == "tree":
            out["trees"].append((x, z))
        elif p["k"] == "barrier" and p["v"] == "gate":
            out["gates"].append((x, z))

L = ["--!nocheck", "-- generated by tools/yangon/city/peoples_park_osm.py from OpenStreetMap (ODbL), 1:1 studs; do not edit", "return {"]
L.append("park = %s," % pl(P))
L.append("water = {" + ",".join('{id=%d,kind="%s",p=%s}' % (i, k, pl(xs)) for i, k, xs in out["water"]) + "},")
L.append("fount = {" + ",".join("{%s,%s,%s,%s,%s,id=%d}" % tuple(f) for f in out["fount"]) + "},")
L.append("box = {" + ",".join('{"%s",%s,%s,%s,%s,%s,id=%d}' % (k, *b, i) for k, b, i in out["box"]) + "},")
L.append("ways = {" + ",\n".join('{"%s",%s,%s}' % (hw, "true" if br else "false", pl(xs)) for hw, br, xs in out["ways"]) + "},")
L.append("trees = " + pl(out["trees"]) + ",")
L.append("gates = " + pl(out["gates"]) + ",")
L.append("}")
open("tools/yangon/PeoplesParkOSM.luau", "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print({k: len(v) for k, v in out.items()}, os.path.getsize("tools/yangon/PeoplesParkOSM.luau"))
from collections import Counter
print(Counter(w[0] for w in out["ways"]), Counter(b[0] for b in out["box"]), [(w[0], w[1]) for w in out["water"]])

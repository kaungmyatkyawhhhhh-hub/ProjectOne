"""mall_life.py: shoppers for the Myanmar Plaza mall (owner's "Fix these first": shoppers), in the street-life format.

Writes src/shared/YangonStreetLifeMall.lua: walking paths round the atrium galleries on GF-3F (two lines between the
balustrade and the shop fronts, clear of the escalator ends), the ground floor's lines across the atrium and out to
the two entrances, and standing spots at shop windows. client/YangonStreetLife reads it as an extra data chunk (the
same line format as tools/yangon/city/streetlife.py: tenths of a stud from ORIGIN, paths as deltas).

    python mall_life.py        (run after mc3d.py; uses its layout)
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from shapely.geometry import Point, Polygon  # noqa: E402

import mc3d  # noqa: E402

ORIGIN = (27900, -6500)  # must equal src/shared/YangonStreetLife.lua's origin
Y0 = 28.8                # mc3d's base (the mall's floors are not on the paving plane)
OX, OZ = 32600.0, -1350.0
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "src", "shared", "YangonStreetLifeMall.lua"))


def world(x, y, z):
    return (OX + x, Y0 + z + 0.05, OZ - y)


def enc(v):
    return int(round(v * 10))


def path_line(pts, wide=False):
    """pts: world (X, Y, Z). 'P m|s count x z y dx dz dy ...'"""
    xs = [(enc(p[0] - ORIGIN[0]), enc(p[2] - ORIGIN[1]), enc(p[1])) for p in pts]
    out = ["P", "m" if wide else "s", str(len(xs)), str(xs[0][0]), str(xs[0][1]), str(xs[0][2])]
    for a, b in zip(xs, xs[1:]):
        out += [str(b[0] - a[0]), str(b[1] - a[1]), str(b[2] - a[2])]
    return " ".join(out)


def main():
    mc3d.build()
    cx, cy = mc3d.DOME
    rx, ry = mc3d.ATR_RX, mc3d.ATR_RY
    ib = Polygon(mc3d.offset_poly(mc3d.POD, -0.8)).buffer(0)
    A_shape = Polygon(mc3d.A).buffer(0.6, join_style=2)
    walk = ib.difference(A_shape).buffer(-1.6)
    lines = []
    # gallery rings: split where a point leaves the walkable floor
    for k in range(mc3d.OPEN_FLOORS):
        z = mc3d.POD_Z[k]
        for extra in (5.4, 6.6):
            seg = []
            for i in range(97):
                a = 2 * math.pi * i / 96
                p = (cx + (rx + extra) * math.cos(a), cy + (ry + extra) * math.sin(a))
                if walk.contains(Point(p)):
                    seg.append(world(p[0], p[1], z))
                else:
                    if len(seg) > 3:
                        lines.append(path_line(seg))
                    seg = []
            if len(seg) > 3:
                lines.append(path_line(seg))
    # ground floor: across the atrium (clear of the escalators at its south end) and out to the entrances
    for a0 in (0.0, math.pi / 4, 3 * math.pi / 4):
        p = (cx + (rx + 4) * math.cos(a0), cy + (ry + 4) * math.sin(a0))
        q = (cx - (rx + 4) * math.cos(a0), cy - (ry + 4) * math.sin(a0))
        pts = [world(p[0] + (q[0] - p[0]) * t / 20, p[1] + (q[1] - p[1]) * t / 20, 0.0) for t in range(21)]
        if all(walk.contains(Point(pt[0] - OX, OZ - pt[2])) for pt in pts):
            lines.append(path_line(pts, wide=True))
    for (m_, n_, w_, t_, L_) in mc3d.ENTR:
        start = (m_[0] + n_[0] * 3.0, m_[1] + n_[1] * 3.0)
        d = (cx - start[0], cy - start[1])
        Ld = math.hypot(*d)
        stop = Ld - (min(rx, ry) + 5.5)
        if stop <= 0:
            continue
        side = (t_[0] * 4.0, t_[1] * 4.0)  # off the lobby's planter
        pts = []
        for s in range(int(stop / 3) + 1):
            u = s * 3 / Ld
            pts.append(world(start[0] + d[0] * u + side[0], start[1] + d[1] * u + side[1], 0.0))
        lines.append(path_line(pts, wide=True))
    # standing spots at shop windows, facing the glass
    n_spot = 0
    for k in range(mc3d.OPEN_FLOORS):
        z = mc3d.POD_Z[k]
        for i in range(24):
            a = 2 * math.pi * (i + 0.5 * (k % 2)) / 24
            p = (cx + (rx + 7.0) * math.cos(a), cy + (ry + 7.0) * math.sin(a))
            if not walk.contains(Point(p)) or (i + k) % 3:
                continue
            X, Y, Z = world(p[0], p[1], z)
            # face outward (toward the shop): model direction (cos a, sin a) -> world (cos a, -sin a); yaw like
            # streetlife.py: atan2(-dx, -dz) in degrees
            dx, dz = math.cos(a), -math.sin(a)
            yaw = math.degrees(math.atan2(-dx, -dz))
            lines.append("S %d %d %d %d s" % (enc(X - ORIGIN[0]), enc(Z - ORIGIN[1]), enc(Y), enc(yaw)))
            n_spot += 1
    body = "\n".join(lines)
    head = ("-- generated by tools/yangon/city/mall_life.py (Myanmar Plaza mall shoppers, read by client/YangonStreetLife "
            "as an extra chunk), do not edit\n")
    open(OUT, "w", newline="\n").write(head + "return [==[\n" + body + "\n]==]\n")
    print("paths", sum(1 for l in lines if l.startswith("P")), "spots", n_spot, "->", OUT)


if __name__ == "__main__":
    main()

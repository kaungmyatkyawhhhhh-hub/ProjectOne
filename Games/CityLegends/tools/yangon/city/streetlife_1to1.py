"""Street life for the 1:1 map (17 Nov 2026, the switch-over): people walking the main roads' pavements.

The old map's src/shared/YangonStreetLife*.lua (streetlife.py, 1.6 studs a metre) is replaced by pavement paths only
(P lines, streetlife.py's format and origin): the middle of both pavements of every roads05 main road (kind route /
side), one point every STEP studs, broken where a point is on another road's carriageway (junction mouths), a
roundabout or a deck (cut samples). Each path runs with its road on its LEFT. The Myanmar Plaza mall's
shoppers (YangonStreetLifeMall1to1.lua, same format) become YangonStreetLifeMall.
shortcut: no parked cars or standing spots (C / S lines) yet; streetlife.py's rules can be ported when there is time.
26 Nov (owner: "people are walking on the road near myanmar plaza"): the 17 Nov paths came from the P1-P3 data before the
J18-J37 passes and the district rebuilds, so whole runs lay on today's carriageways. Now every run is also cut to the
surfaces IN THE PLACE (walkers_check.Clipper: each point on a pavement box, taking its height; no walker band on a road,
deck or median box), from the Studio dumps in build/city_1to1/walkers_26nov/. Re-dump them after any road swap, re-run
this, then walkers_check.py must print 0.

    YANGON_SCALE=1to1 python streetlife_1to1.py <roads05 tag of the whole network>
"""
import json, math, os, sys

from shapely.geometry import Point
from shapely.strtree import STRtree

import geo
from walkers_check import Clipper, decode, OUT as WC_OUT
from roads05_clear import road_polys

OX, OZ = 27900, -6500   # streetlife.py's origin (decimetres from here)
STEP = 16.0
MAXCHARS = 185000


def main(tag):
    data = json.load(open(os.path.join(geo.BUILD, 'city_1to1', 'roads05_' + tag, 'roads.json'), encoding='utf-8'))
    cw, _ = road_polys(data)
    cut = {k: set(v) for k, v in data['cut'].items()}
    tree = STRtree([g for _, g in cw])
    lines = []

    def on_other(name, x, z):
        p = Point(x, z)
        return any(cw[k][0] != name and cw[k][1].contains(p) for k in tree.query(p))
    for r in data['roads']:
        if r['kind'] not in ('route', 'side'):
            continue
        s, c = r['s'], cut.get(r['name'], set())
        for side, walk in ((1, r.get('walkR', 7.5)), (-1, r.get('walkL', 7.5))):
            run, last = [], None
            idx = range(len(s)) if side == 1 else range(len(s) - 1, -1, -1)
            for i in idx:
                q = s[i]
                off = (q[7] + walk / 2) if side == 1 else -(q[6] + walk / 2)
                x, z = q[0] - q[4] * off, q[2] + q[3] * off
                ok = i not in c and not on_other(r['name'], x, z)
                if ok and (last is None or math.hypot(x - last[0], z - last[1]) >= STEP):
                    run.append((x, q[1] + 0.5, z))
                    last = (x, z)
                elif not ok:
                    if len(run) >= 4:
                        lines.append(run)
                    run, last = [], None
            if len(run) >= 4:
                lines.append(run)
    raw = len(lines)
    clip = Clipper(decode(os.path.join(WC_OUT, 'roadboxes_place.txt')) + decode(os.path.join(WC_OUT, 'paveboxes_place.txt')))
    lines = [r for run in lines for r in clip.clip(run)]
    print('%d raw runs -> %d after the place clip' % (raw, len(lines)))
    out = []
    for run in lines:
        q = [(round((x - OX) * 10), round((z - OZ) * 10), round(y * 10)) for x, y, z in run]
        bits = ['P', 'm', str(len(q)), str(q[0][0]), str(q[0][1]), str(q[0][2])]
        for a, b in zip(q, q[1:]):
            bits += [str(b[0] - a[0]), str(b[1] - a[1]), str(b[2] - a[2])]
        out.append(' '.join(bits))
    chunks, cur = [], []
    for ln in out:
        if sum(len(x) + 1 for x in cur) + len(ln) > MAXCHARS:
            chunks.append(cur)
            cur = []
        cur.append(ln)
    chunks.append(cur)
    SH = os.path.join(geo.ROOT, 'src', 'shared')
    names = ['YangonStreetLife'] + ['YangonStreetLife%d' % (k + 1) for k in range(1, len(chunks))]
    head = '-- generated by tools/yangon/city/streetlife_1to1.py (1:1 Yangon pavement walkers; OpenStreetMap contributors, ODbL): part %d of %d, do not edit\n'
    for k, (name, ch) in enumerate(zip(names, chunks)):
        body = '\n'.join(ch)
        if k == 0:
            txt = head % (1, len(chunks)) + 'return {\n\tmore = { %s },\n\torigin = { %d, %d },\n\tdata = [==[\n%s\n]==],\n}\n' % (
                ', '.join('"%s"' % n for n in names[1:]), OX, OZ, body)
        else:
            txt = head % (k + 1, len(chunks)) + 'return [==[\n%s\n]==]\n' % body
        open(os.path.join(SH, name + '.lua'), 'w', encoding='utf-8', newline='\n').write(txt)
    print('%d paths, %d points, %d modules' % (len(lines), sum(len(r) for r in lines), len(chunks)))


if __name__ == '__main__':
    assert geo.ONE_TO_ONE, 'run with YANGON_SCALE=1to1'
    main(sys.argv[1])

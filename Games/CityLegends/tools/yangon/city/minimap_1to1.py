"""The minimap picture tiles for the 1:1 map (17 Nov 2026, the switch-over): a simple drawn night map, d12_minimap's look.

Ground, OSM water, the building shells (buildings_<tag>/Shell_*.txt boxes), the roads05 carriageways (main roads gold,
streets light grey) and pavements, the roundabouts. SPP studs a pixel, 1024 x 512 tiles; empty tiles are left out.

    YANGON_SCALE=1to1 python minimap_1to1.py <roads05 tags> <district> [<district> ...]   -> build/minimap_1to1/tile_<c>_<r>.png
    YANGON_SCALE=1to1 python minimap_1to1.py --lua ids.json                                -> src/client/YangonMapArt.lua
"""
import json, math, os, sys

from PIL import Image, ImageDraw

import geo
from roads05_clear import road_polys, shells

OUT = os.path.join(geo.ROOT, 'imports', 'sync', 'minimap_1to1')  # (imports/: the folder approved for Open Cloud uploads)
SPP = 12.0  # (shortcut: 12 studs a pixel keeps it to ~8 uploads; 4-6 for a sharper map when there is time)
TW, TH = 1024, 512
GROUND, WATER, WATER_EDGE = (34, 44, 42), (14, 36, 64), (30, 70, 108)
BUILDING, PAVEMENT, STREET, ROUTE = (60, 68, 84), (64, 68, 80), (156, 164, 180), (222, 184, 98)


def rings(p):
    if p and isinstance(p[0][0], (int, float)):
        yield p
    else:
        for q in p:
            yield from rings(q)


def build(tag, districts):
    data = json.load(open(os.path.join(geo.BUILD, 'city_1to1', 'roads05_' + tag, 'roads.json'), encoding='utf-8'))
    cw, pv = road_polys(data)
    kind = {r['name']: r['kind'] for r in data['roads']}
    xs = [q[0] for r in data['roads'] for q in r['s']]
    zs = [q[2] for r in data['roads'] for q in r['s']]
    x0 = math.floor((min(xs) - 300) / (TW * SPP)) * TW * SPP
    z0 = math.floor((min(zs) - 300) / (TH * SPP)) * TH * SPP
    cols = math.ceil((max(xs) + 300 - x0) / (TW * SPP))
    rows = math.ceil((max(zs) + 300 - z0) / (TH * SPP))
    W, H = cols * TW, rows * TH
    img = Image.new('RGB', (W, H), GROUND)
    d = ImageDraw.Draw(img)
    px = lambda x, z: ((x - x0) / SPP, (z - z0) / SPP)
    for a in geo.load('areas'):
        t = a.get('t', {})
        if t.get('natural') == 'water' or t.get('water'):
            for ring in rings(a['p']):
                pts = [px(*geo.world(lon, lat)) for lon, lat in ring]
                if len(pts) > 2:
                    d.polygon(pts, fill=WATER, outline=WATER_EDGE)
    for t in districts:
        for s in shells(t):
            d.polygon([px(x, z) for x, z in s.exterior.coords], fill=BUILDING)
    for polys, colour in ((pv, lambda n: PAVEMENT), (cw, lambda n: ROUTE if kind.get(n) in ('route', 'side') else STREET)):
        for name, g in polys:
            for poly in getattr(g, 'geoms', [g]):
                if poly.geom_type == 'Polygon':
                    d.polygon([px(x, z) for x, z in poly.exterior.coords], fill=colour(name))
    os.makedirs(OUT, exist_ok=True)
    kept = []
    for c in range(cols):
        for r in range(rows):
            tile = img.crop((c * TW, r * TH, (c + 1) * TW, (r + 1) * TH))
            if tile.getcolors(4) is not None:  # nothing but ground
                continue
            tile.save(os.path.join(OUT, 'tile_%d_%d.png' % (c, r)))
            kept.append((c, r))
    img.resize((W // 8, H // 8)).save(os.path.join(OUT, 'preview.png'))
    json.dump(dict(x0=x0, z0=z0, cols=cols, rows=rows, tiles=kept, map=[min(xs), min(zs), max(xs), max(zs)]),
              open(os.path.join(OUT, 'layout.json'), 'w'))
    print('%d x %d tiles, %d kept' % (cols, rows, len(kept)))


def lua(ids_path):
    L = json.load(open(os.path.join(OUT, 'layout.json')))
    ids = json.load(open(ids_path))
    m = L['map']
    out = ['-- generated by tools/yangon/city/minimap_1to1.py: do not edit',
           "-- the 1:1 Yangon map as picture tiles (world studs); the rim and the arrow are MinimapArt's",
           'return {',
           '\tx0 = %d, z0 = %d, tileStuds = Vector2.new(%d, %d), cols = %d, rows = %d,' % (L['x0'], L['z0'], TW * SPP, TH * SPP, L['cols'], L['rows']),
           '\tback = Color3.fromRGB(%d, %d, %d),' % GROUND,
           '\tmap = { x0 = %d, z0 = %d, x1 = %d, z1 = %d },' % tuple(m),
           '\ttiles = {']
    for c, r in L['tiles']:
        out.append('\t\t{ col = %d, row = %d, image = "%s" },' % (c, r, ids['tile_%d_%d' % (c, r)]))
    out += ['\t},', '}', '']
    open(os.path.join(geo.ROOT, 'src', 'client', 'YangonMapArt.lua'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))


if __name__ == '__main__':
    assert geo.ONE_TO_ONE, 'run with YANGON_SCALE=1to1'
    if sys.argv[1] == '--lua':
        lua(sys.argv[2])
    else:
        build(sys.argv[1], sys.argv[2:])

"""lanes_1to1.py (2026-11-16): the 1:1 pilot districts' traffic lanes into the game, as their own area.

    YANGON_SCALE=1to1 python lanes_1to1.py P1 [P2 ...]      (run from Games/CityLegends/tools/yangon/city, after roads.py)

roads.py writes each pilot's lanes as build/city_1to1/YangonLanesB<tag>_<k>.lua in the old map's GLOBAL numbering (`first`
after every module in src/shared and the batches), which moves whenever another map's module changes. The game reads the
1:1 frame's lanes from src/shared/YangonLanes1to1_<k>.lua instead: the same lanes and links, numbered from 1 within the
1:1 set (pilots in the order given, each continuing the last), and RivieraTraffic.build adds them after everything else
with the lane count at that point as the offset. Every module stays under 190,000 characters (Studio's limit is 200,000).
Old src/shared/YangonLanes1to1_*.lua files are replaced.
"""
import os
import re
import sys

import geo

assert geo.ONE_TO_ONE, 'run with YANGON_SCALE=1to1'
SRC = os.path.join(geo.ROOT, 'src', 'shared')
B11 = os.path.join(geo.BUILD, 'city_1to1')
LINK = re.compile(r'^(\s*)\{ (\d+), (\d+), (\d+), (\d+) \},\s*$')


def modules(tag):
    out = []
    k = 1
    while True:
        p = os.path.join(B11, 'YangonLanesB%s_%d.lua' % (tag, k))
        if not os.path.exists(p):
            return out
        out.append(p)
        k += 1


def main(tags):
    files = [p for t in tags for p in modules(t)]
    assert files, 'no lane modules for %s in %s' % (tags, B11)
    first0 = None
    expect = None
    written = []
    for f in os.listdir(SRC):
        if re.match(r'YangonLanes1to1_\d+\.lua$', f):
            os.remove(os.path.join(SRC, f))
    nlanes = nlinks = 0
    for k, p in enumerate(files, 1):
        src = open(p, encoding='utf-8').read()
        first = int(re.search(r'\n\tfirst = (\d+),', src).group(1))
        if first0 is None:
            first0 = first
        if expect is not None:
            assert first == expect, '%s: first %d, expected %d (pilots out of order or a stale module)' % (p, first, expect)
        n = len(re.findall(r'\{ road = ', src))
        expect = first + n
        base = first0 - 1
        lines = src.split('\n')
        out = ['-- generated by tools/yangon/city/lanes_1to1.py from %s (roads.py, OSM ODbL): do not edit' % os.path.basename(p),
               '-- the 1:1 Yangon frame\'s traffic lanes, module %d of %d; numbered from 1 within the 1:1 set (`first`, links too);' % (k, len(files)),
               '-- RivieraTraffic.build adds them after every other module']
        body = False
        for ln in lines:
            if ln.startswith('return {'):
                body = True
            if not body:
                continue
            m = re.match(r'^\tfirst = (\d+),$', ln)
            if m:
                ln = '\tfirst = %d,' % (int(m.group(1)) - base)
            m = LINK.match(ln)
            if m:
                a, ka, b, kb = int(m.group(2)), m.group(3), int(m.group(4)), m.group(5)
                assert a > base and b > base, ('a link out of the 1:1 set', ln)
                ln = '%s{ %d, %s, %d, %s },' % (m.group(1), a - base, ka, b - base, kb)
                nlinks += 1
            out.append(ln)
        text = '\n'.join(out)
        if not text.endswith('\n'):
            text += '\n'
        assert len(text) < 190000, (p, len(text))
        dst = os.path.join(SRC, 'YangonLanes1to1_%d.lua' % k)
        open(dst, 'w', encoding='utf-8', newline='\n').write(text)
        written.append((dst, len(text), n))
        nlanes += n
    for dst, c, n in written:
        print('%s  %d chars  %d lanes' % (os.path.relpath(dst, geo.ROOT), c, n))
    print('1:1 lanes %d, links %d, from %s' % (nlanes, nlinks, ' '.join(tags)))


if __name__ == '__main__':
    main(sys.argv[1:] or ['P1'])

# Writes src/client/BrandMarks.lua from tools/brand_marks/marks.json (run from Games/CityLegends).
# marks.json comes from measure.py + collect.py + check.py (see README.md in this folder).
import json, sys

sys.path.insert(0, "tools/brand_marks")
from picks import KEEP

D = json.load(open("tools/brand_marks/marks.json"))


def n(x):
    if abs(x) < 5e-5:
        return "0"
    return ("%.4f" % x).rstrip("0").rstrip(".")


def v3(a):
    return "Vector3.new(%s, %s, %s)" % tuple(n(x) for x in a)


def c3(c):
    return "Color3.fromRGB(%d, %d, %d)" % tuple(max(0, min(255, round(x * 255))) for x in c)


out = [
    "-- Generated by tools/brand_marks/to_lua.py from tools/brand_marks/marks.json: do not edit by hand.",
    "-- Real makers' badges, logos and names on each converted car (owner, 2026-10-17: \"remove the logos",
    "-- and badge and name ... for brands like bmw, mercedes, lexus make a similar but not too close but",
    "-- still recognizable logo\"), measured on the converted files. Metres in the car's own frame:",
    "-- from the middle of its four wheel centres, along right / up / back. CarSkin hides the badge parts",
    "-- (hide: by name, and by size where the name is shared), covers logos printed on the paint or a",
    "-- plate (covers: blank patches in the colour around them, or our own emblem), the wheel centre",
    "-- caps (caps) and the steering wheel's hub (hub: from the middle of the wheel part, in its own",
    "-- frame: x right, y up, z towards the driver). brand: whose fictional emblem goes on.",
    "export type Cover = { emblem: boolean, disc: boolean, at: Vector3, face: Vector3, w: number, h: number, color: Color3 }",
    "export type Cap = { r: number, surface: number, color: Color3 }",
    "export type Marks = {",
    "\twb: number,",
    "\tbrand: string?,",
    "\thide: { { name: string, size: Vector3? } },",
    "\tkeep: { string }?,",
    "\tcovers: { Cover },",
    "\tcaps: { [string]: Cap },",
    "\thub: { at: Vector3, face: Vector3, r: number, color: Color3 }?,",
    "}",
    "",
    "return {",
]
for car in sorted(D):
    d = D[car]
    out.append("\t%s = {" % car)
    out.append("\t\twb = %s," % n(d["wb"]))
    if d["brand"]:
        out.append('\t\tbrand = "%s",' % d["brand"])
    hide = []
    for h in d["hide"]:
        if "size" in h:
            hide.append('{ name = "%s", size = %s }' % (h["name"], v3(h["size"])))
        else:
            hide.append('{ name = "%s" }' % h["name"])
    out.append("\t\thide = { %s }," % ", ".join(hide) if hide else "\t\thide = {},")
    if KEEP.get(car):
        out.append("\t\tkeep = { %s }, -- badge-named, but more than badges (covered instead)" % ", ".join('"%s"' % k for k in KEEP[car]))
    out.append("\t\tcovers = {")
    for c in d["covers"]:
        out.append("\t\t\t{ emblem = %s, disc = %s, at = %s, face = %s, w = %s, h = %s, color = %s }," % (
            "true" if c["kind"] == "emblem" else "false", "true" if c["shape"] == "disc" else "false",
            v3(c["at"]), v3(c["face"]), n(c["w"]), n(c["h"]), c3(c["color"])))
    out.append("\t\t},")
    out.append("\t\tcaps = {")
    for k in sorted(d["caps"]):
        cp = d["caps"][k]
        out.append("\t\t\t%s = { r = %s, surface = %s, color = %s }," % (k, n(cp["r"]), n(cp["surface"]), c3(cp["color"])))
    out.append("\t\t},")
    h = d["hub"]
    if h:
        out.append("\t\thub = { at = %s, face = %s, r = %s, color = %s }," % (v3(h["local"]), v3(h["face"]), n(h["r"]), c3(h["color"])))
    out.append("\t},")
out.append("} :: { [string]: Marks }")
open("src/client/BrandMarks.lua", "w").write("\n".join(out) + "\n")
print("wrote", len(D), "cars")

# Writes src/client/TailLights.lua from the Blender scan (scan.py: rear parts coloured red or named
# as tail / brake lights) and the lamp spots picked on rear views (picks.py -> spots_<car>.json).
import json, glob, re, os, sys
P = json.load(open("/tmp/claude-0/logo/parts.json"))
EXCL = re.compile(r"alumin|chrome|plas$|details|baked|orange|signal|_ad$|bucket", re.I)
NAMED = re.compile(r"brake|stop|taillight|tail_light|rearlight", re.I)
out = {}
for f in sorted(glob.glob("/tmp/claude-0/tail/*.json")):
    base = os.path.basename(f)
    if base.startswith("spots_"):
        continue
    d = json.load(open(f))
    car = d["car"]
    shells = []
    for p in d["parts"]:
        if EXCL.search(p["name"]) or p["rearFrac"] < 0.85 or p["dims"][2] > 1.5:  # a lamp part that runs to the front
            continue
        if not (p["red"] >= 0.3 or NAMED.search(p["name"])):
            continue
        name = re.sub(r"\.\d\d\d$", "", p["name"])
        same = [q for q in P[car] if q[0] == name]
        if not same:
            print("NOPART", car, name); continue
        if len(same) == 1:
            shells.append({"name": name}); continue
        best = min(same, key=lambda q: sum(abs(q[1 + i] - p["dims"][i]) for i in range(3)))
        shells.append({"name": name, "size": [round(x, 4) for x in best[1:4]]})
    out[car] = {"shells": shells, "spots": []}
for f in glob.glob("/tmp/claude-0/tail/spots_*.json"):
    d = json.load(open(f))
    out.setdefault(d["car"], {"shells": [], "spots": []})
    out[d["car"]]["wb"] = d["wb"]
    out[d["car"]]["spots"] = [{"at": c["at"], "face": c["face"], "w": c["w"], "h": c["h"]} for c in d["covers"]]
json.dump(out, open(sys.argv[1] + "/tails.json", "w"), indent=1)
def n(x):
    return "0" if abs(x) < 5e-5 else ("%.4f" % x).rstrip("0").rstrip(".")
def v3(a): return "Vector3.new(%s, %s, %s)" % tuple(n(x) for x in a)
L = ["-- Generated by tools/tail_lights/to_lua.py: do not edit by hand.",
     "-- Each converted car's tail lamps (owner, 2026-10-17: \"add rear tail light for all cars\"): the",
     "-- model's own lamp parts (shells: by name, and by size where the name is shared), which CarSkin",
     "-- covers with a red glowing copy, or, where the lamps are only painted on, lamp spots picked on",
     "-- the car's rear (spots: metres from the middle of the four wheel centres, along right / up /",
     "-- back, facing out of the car; wb: the wheelbase they were measured at).",
     "export type Spot = { at: Vector3, face: Vector3, w: number, h: number }",
     "export type Tails = { shells: { { name: string, size: Vector3? } }, spots: { Spot }, wb: number? }",
     "", "return {"]
for car in sorted(out):
    d = out[car]
    if not d["shells"] and not d["spots"]:
        continue
    L.append("\t%s = {" % car)
    L.append(("\t\tshells = { %s }," if d["shells"] else "\t\tshells = {},%s") % ", ".join(('{ name = "%s", size = %s }' % (s["name"], v3(s["size"]))) if "size" in s else ('{ name = "%s" }' % s["name"]) for s in d["shells"]))
    if d["spots"]:
        L.append("\t\twb = %s," % n(d["wb"]))
        L.append("\t\tspots = {")
        for s in d["spots"]:
            L.append("\t\t\t{ at = %s, face = %s, w = %s, h = %s }," % (v3(s["at"]), v3(s["face"]), n(s["w"]), n(s["h"])))
        L.append("\t\t},")
    else:
        L.append("\t\tspots = {},")
    L.append("\t},")
L.append("} :: { [string]: Tails }")
open(sys.argv[2], "w").write("\n".join(L) + "\n")
print(sum(1 for c in out.values() if c["shells"] or c["spots"]), "cars")

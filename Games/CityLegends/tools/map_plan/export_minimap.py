"""
The Riviera on the minimap (owner 2026-11-02: venues moved to Monaco, players start there).

From build/riviera/far.json (land cells) and roads.json (centre lines): the land as horizontal runs
of 128-stud cells (one frame each), the roads as centre lines simplified to within 5 studs (one frame
per piece). Output: src/shared/RivieraMap.lua, read by src/client/Minimap.lua.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")


def simplify(pts, tol):
    # Douglas-Peucker on (x, z)
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    dx, dz = b[0] - a[0], b[1] - a[1]
    n = math.hypot(dx, dz) or 1e-9
    best, bi = -1, 0
    for i in range(1, len(pts) - 1):
        p = pts[i]
        d = abs((p[0] - a[0]) * dz - (p[1] - a[1]) * dx) / n
        if d > best:
            best, bi = d, i
    if best <= tol:
        return [a, b]
    left = simplify(pts[: bi + 1], tol)
    right = simplify(pts[bi:], tol)
    return left[:-1] + right


def main():
    far = json.load(open(os.path.join(ROOT, "build", "riviera", "far.json")))
    step, x0, z0 = far["step"], far["x0"], far["z0"]
    rows = {}
    for vi, vj, _ in far["cells"]:
        rows.setdefault(vj, []).append(vi)
    runs = []
    for vj, cols in sorted(rows.items()):
        cols.sort()
        start = prev = cols[0]
        for c in cols[1:] + [None]:
            if c is not None and c == prev + 1:
                prev = c
                continue
            runs.append((x0 + start * step, z0 + vj * step, x0 + (prev + 1) * step, z0 + (vj + 1) * step))
            if c is not None:
                start = prev = c
    data = json.load(open(os.path.join(ROOT, "build", "riviera", "roads.json")))
    roads = []
    for r in data["roads"]:
        pts = [(s[0], s[2]) for s in r["s"]]
        sp = simplify(pts, 5.0)
        roads.append((r["kind"], sp))
    out = ["-- generated by tools/map_plan/export_minimap.py: do not edit", "return {", "\tland = {"]
    for a in runs:
        out.append("\t\t{ %d, %d, %d, %d }," % a)
    out.append("\t},")
    out.append("\troads = {")
    for kind, sp in roads:
        flat = ",".join("%d,%d" % (round(p[0]), round(p[1])) for p in sp)
        out.append('\t\t{ kind = "%s", pts = { %s } },' % (kind, flat))
    out.append("\t},")
    out.append("}")
    path = os.path.join(ROOT, "src", "shared", "RivieraMap.lua")
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"{len(runs)} land runs, {sum(len(sp) - 1 for _, sp in roads)} road pieces -> {os.path.getsize(path)} bytes")


if __name__ == "__main__":
    main()
